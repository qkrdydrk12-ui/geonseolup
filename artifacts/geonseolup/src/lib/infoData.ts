export function getArticle(slug: string): InfoArticle | undefined {
  return INFO_ARTICLES.find((a) => a.slug === slug);
}

// 목록 표시용: 새 글일수록 배열 뒤에 추가되므로, 뒤집어서 최신 글이 맨 위에 오게 한다.
export const INFO_ARTICLES_NEWEST_FIRST: InfoArticle[] = [...INFO_ARTICLES].reverse();

// 관리자가 수정한 내용(override)을 서버에서 받아 원본과 병합한다.
// 서버 조회 실패 시에는 원본을 그대로 보여준다 (글이 안 보이는 것보단 낫다).
import { useEffect, useState } from 'react';

let _overridesCache: Record<string, InfoArticle> | null = null;

export async function fetchInfoOverrides(): Promise<Record<string, InfoArticle>> {
  if (_overridesCache) return _overridesCache;
  try {
    const res = await fetch('/api/info/overrides');
    if (!res.ok) return {};
    const data = await res.json();
    _overridesCache = (data?.overrides ?? {}) as Record<string, InfoArticle>;
    return _overridesCache;
  } catch {
    return {};
  }
}

export function clearInfoOverridesCache() {
  _overridesCache = null;
}

// 관리자 override의 본문 블록에 이미지 정보가 빠져 있으면 (예: 이미지가 나중에 추가된 글)
// 같은 위치의 원본 블록 이미지를 유지한다. 이미지가 사라지는 사고 방지.
function mergeWithOverride(base: InfoArticle, ov: InfoArticle): InfoArticle {
  const merged = { ...base, ...ov };
  if (Array.isArray(ov.body) && Array.isArray(base.body)) {
    merged.body = ov.body.map((b, i) =>
      !b.image && base.body[i]?.image ? { ...b, image: base.body[i].image } : b
    );
  }
  return merged;
}

export function useInfoArticles(): InfoArticle[] {
  const [articles, setArticles] = useState<InfoArticle[]>(INFO_ARTICLES_NEWEST_FIRST);
  useEffect(() => {
    let alive = true;
    fetchInfoOverrides().then((overrides) => {
      if (!alive || !Object.keys(overrides).length) return;
      setArticles(INFO_ARTICLES_NEWEST_FIRST.map((a) => overrides[a.slug] ? mergeWithOverride(a, overrides[a.slug]) : a));
    });
    return () => { alive = false; };
  }, []);
  return articles;
}

